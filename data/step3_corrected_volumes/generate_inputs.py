#!/usr/bin/env python3
"""Generate volume-corrected constant-coupling production inputs."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from data.step3_scan import generate_inputs as step3  # noqa: E402


SWEEPS = 20_000
TIMING_SWEEPS = 100
PRODUCTION_SEEDS = (
    1139865066,
    1786727755,
    1777987394,
    1986906165,
    32943504,
    1111774376,
    350847387,
    1543348040,
)
TIMING_SEED = 1747406840
KLFT_COMMIT = "7eed1f7d9bb0948621a2d4020706d19c56406001"
HEATBATH_SHA256 = (
    "41fc9502a1f74106894ff077a3d9e2905dd6a75f7bf65c96971150a74132ed57"
)
GRID = (
    step3.Ensemble("constant_lambda_nt3_volume_corrected", 3, "5.4", 176),
    step3.Ensemble("constant_lambda_nt4_volume_corrected", 4, "7.2", 256),
)


def input_text(ensemble: step3.Ensemble, seed: int, sweeps: int) -> str:
    """Return one input using the validated Step-3 observable set."""
    text = step3.input_text(ensemble, seed, sweeps)
    return text.replace(
        "# Generated by data/step3_scan/generate_inputs.py",
        "# Generated by data/step3_corrected_volumes/generate_inputs.py",
        1,
    )


def previous_seeds() -> set[int]:
    """Return production seeds used by earlier Step-3 campaigns."""
    seeds: set[int] = set()
    for relative in (
        "data/step3_scan/manifest.tsv",
        "data/step3_fv160/manifest.tsv",
    ):
        with (ROOT / relative).open(encoding="utf-8", newline="") as stream:
            seeds.update(
                int(row["seed"])
                for row in csv.DictReader(stream, delimiter="\t")
            )
    seeds.update((step3.TIMING_SEED, 376035314))
    return seeds


def generate(output: Path) -> list[Path]:
    """Write eight production inputs and one timing input without overwriting."""
    seeds = (*PRODUCTION_SEEDS, TIMING_SEED)
    if len(PRODUCTION_SEEDS) != 4 * len(GRID) or len(set(seeds)) != len(seeds):
        raise RuntimeError("corrected-volume seeds are not unique")
    if set(seeds) & previous_seeds():
        raise RuntimeError("corrected-volume campaign reuses a Step-3 seed")

    pending: list[tuple[Path, str]] = []
    rows: list[dict[str, object]] = []
    array_index = 0
    for ensemble_index, ensemble in enumerate(GRID):
        for chain_index in range(4):
            seed = PRODUCTION_SEEDS[4 * ensemble_index + chain_index]
            run = f"{step3.ensemble_name(ensemble)}/seed_{seed}"
            relative_input = Path(run) / "input.yaml"
            text = input_text(ensemble, seed, SWEEPS)
            pending.append((output / relative_input, text))
            rows.append(
                {
                    "array_index": array_index,
                    "run": run,
                    "input": relative_input.as_posix(),
                    "purpose": ensemble.purpose,
                    "physical_Nt": ensemble.nt,
                    "stored_L2": ensemble.nt + 1,
                    "Ns": ensemble.ns,
                    "beta": ensemble.beta,
                    "lambda_squared_tree": format(
                        step3.lambda_squared_tree(ensemble), ".12f"
                    ),
                    "chain_index": chain_index,
                    "seed": seed,
                    "sweeps": SWEEPS,
                    "measurement_interval": step3.MEASUREMENT_INTERVAL,
                    "dirichlet_suite_measurement_interval": (
                        step3.SUITE_MEASUREMENT_INTERVAL
                    ),
                    "input_sha256": step3.sha256_text(text),
                }
            )
            array_index += 1

    timing = input_text(GRID[-1], TIMING_SEED, TIMING_SWEEPS)
    pending.extend(
        (
            (output / "manifest.tsv", step3.manifest_text(rows)),
            (output / "timing" / "input.yaml", timing),
            (
                output / "timing" / "sha256.txt",
                f"{step3.sha256_text(timing)}  input.yaml\n",
            ),
            (output / "klft_commit.txt", f"{KLFT_COMMIT}\n"),
            (output / "heatbath_sha256.txt", f"{HEATBATH_SHA256}\n"),
        )
    )
    existing = [path for path, _ in pending if path.exists()]
    if existing:
        raise FileExistsError(f"refusing to overwrite {existing[0]}")
    for path, text in pending:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="")
    return [path for path, _ in pending]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    paths = generate(args.output)
    print("wrote eight production inputs and one timing input")
    print(f"manifest: {args.output / 'manifest.tsv'}")
    print(f"files created: {len(paths)}")


if __name__ == "__main__":
    main()
