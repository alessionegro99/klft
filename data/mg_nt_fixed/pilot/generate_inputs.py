def previous_seeds() -> set[int]:
    """Return seeds recorded by campaigns outside ``mg_nt_fixed``."""
    seeds: set[int] = set()
    for manifest in (ROOT / "data").rglob("manifest.tsv"):
        if "mg_nt_fixed" in manifest.parts:
            continue
        with manifest.open(encoding="utf-8", newline="") as stream:
            reader = csv.DictReader(stream, delimiter="\t")
            if reader.fieldnames is None or "seed" not in reader.fieldnames:
                continue
            seeds.update(int(row["seed"]) for row in reader)
    return seeds


def generate(output: Path) -> list[Path]:
    """Write all pilot inputs and refuse before changing any existing target."""
    reserved = (
        *PRODUCTION_SEEDS,
        *CONFIRMATION_SEEDS,
        TIMING_SEED,
        *SPARE_BRACKET_SEEDS,
    )
    if len(PRODUCTION_SEEDS) != 4 * len(GRID):
        raise RuntimeError("the pilot requires exactly four seeds per point")
    if len(set(reserved)) != len(reserved):
        raise RuntimeError("fixed-mass campaign seeds are not unique")
    collision = set(reserved) & previous_seeds()
    if collision:
        raise RuntimeError(f"fixed-mass seed reuses an earlier seed: {min(collision)}")

    uv_lock_sha256 = sha256_file(ROOT / "uv.lock")
    pending: list[tuple[Path, str]] = []
    rows: list[dict[str, object]] = []
    array_index = 0
    for ensemble_index, ensemble in enumerate(GRID):
        for chain_index in range(4):
            seed = PRODUCTION_SEEDS[4 * ensemble_index + chain_index]
            name = ensemble_name(ensemble)
            run = f"mg_nt_fixed/{name}/seed_{seed}"
            relative_input = Path(name) / f"seed_{seed}" / "input.yaml"
            text = input_text(ensemble, seed)
            pending.append((output / relative_input, text))
            rows.append(
                {
                    "array_index": array_index,
                    "campaign_type": CAMPAIGN_TYPE,
                    "target_c": ensemble.target_c,
                    "run": run,
                    "input": relative_input.as_posix(),
                    "purpose": "pilot_bracket",
                    "physical_Nt": ensemble.nt,
                    "stored_L2": ensemble.nt + 1,
                    "Ns": ensemble.ns,
                    "beta": ensemble.beta,
                    "chain_index": chain_index,
                    "seed": seed,
                    "sweeps": SWEEPS,
                    "measurement_interval": MEASUREMENT_INTERVAL,
                    "dirichlet_suite_measurement_interval": (
                        SUITE_MEASUREMENT_INTERVAL
                    ),
                    "input_sha256": sha256_text(text),
                    "heatbath_sha256": HEATBATH_SHA256,
                    "klft_commit": KLFT_COMMIT,
                    "uv_lock_sha256": uv_lock_sha256,
                }
            )
            array_index += 1

    timing_ensemble = GRID[7]
    timing_text = input_text(timing_ensemble, TIMING_SEED, TIMING_SWEEPS)
    pending.extend(
        (
            (output / "manifest.tsv", manifest_text(rows)),
            (output / "prior_points.tsv", prior_points_text()),
            (output / "timing" / "input.yaml", timing_text),
            (
                output / "timing" / "sha256.txt",
                f"{sha256_text(timing_text)}  input.yaml\n",
            ),
            (output / "klft_commit.txt", f"{KLFT_COMMIT}\n"),
            (output / "heatbath_sha256.txt", f"{HEATBATH_SHA256}\n"),
            (output / "uv_lock_sha256.txt", f"{uv_lock_sha256}\n"),
            (output / "master_seed.txt", f"{MASTER_SEED}\n"),
            (
                output / "reserved_seeds.tsv",
                "purpose\tseed\n"
                + "".join(
                    f"confirmation_chain_{index}\t{seed}\n"
                    for index, seed in enumerate(CONFIRMATION_SEEDS)
                )
                + f"timing\t{TIMING_SEED}\n"
                + "".join(
                    f"spare_bracket_chain_{index}\t{seed}\n"
                    for index, seed in enumerate(SPARE_BRACKET_SEEDS)
                ),
            ),
        )
    )
    existing = [path for path, _ in pending if path.exists()]
    if existing:
        raise FileExistsError(f"refusing to overwrite {existing[0]}")
    for path, text in pending:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="")
    return [path for path, _ in pending]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    paths = generate(args.output)
    print("wrote 100 production inputs and one timing input")
    print(f"manifest: {args.output / 'manifest.tsv'}")
    print(f"files created: {len(paths)}")


if __name__ == "__main__":
    main()
