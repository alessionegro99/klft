def manifest_text(rows: list[dict[str, object]]) -> str:
    """Serialize manifest rows with a stable column order and LF endings."""
    columns = (
        "array_index",
        "campaign_type",
        "target_c",
        "run",
        "input",
        "purpose",
        "physical_Nt",
        "stored_L2",
        "Ns",
        "beta",
        "chain_index",
        "seed",
        "sweeps",
        "measurement_interval",
        "dirichlet_suite_measurement_interval",
        "input_sha256",
        "heatbath_sha256",
        "klft_commit",
        "uv_lock_sha256",
    )
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(
        stream, fieldnames=columns, delimiter="\t", lineterminator="\n"
    )
    writer.writeheader()
    writer.writerows(rows)
    return stream.getvalue()


