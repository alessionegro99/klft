def beta_tag(beta: str) -> str:
    """Return the filesystem-safe coupling tag."""
    return beta.replace(".", "p")


def ensemble_name(ensemble: Ensemble) -> str:
    """Return the canonical ensemble directory name."""
    return f"Nt_{ensemble.nt}_Ns_{ensemble.ns}_b_{beta_tag(ensemble.beta)}"


def sha256_text(text: str) -> str:
    """Return the SHA-256 digest of UTF-8 text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_file(path: Path) -> str:
    """Return the SHA-256 digest of one file."""
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


