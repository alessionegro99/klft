#!/usr/bin/env python3
"""Generate independent heatbath inputs for the Dirichlet thesis study."""

from __future__ import annotations

import argparse
from pathlib import Path


DEFAULT_SEEDS = (32091, 90517, 177013, 515029)
BETA = 12.15266


def beta_tag(beta: float) -> str:
    """Return a filesystem-safe decimal coupling."""
    return str(beta).replace(".", "p")


def input_text(
    *,
    nx: int,
    ny: int,
    nt: int,
    seed: int,
    sweeps: int,
    measurement_interval: int,
    all_heights: bool,
    quality_max_r: int = 0,
) -> str:
    """Return one 3D SU(2) heatbath input.

    ``nt`` is the physical slab thickness. KLFT stores ``nt + 1`` temporal
    sites because the upper Dirichlet surface is an explicit stored slice.
    """
    if nx < 1 or ny < 1 or nt < 1:
        raise ValueError("nx, ny, and nt must be positive")
    if sweeps < 1 or measurement_interval < 1:
        raise ValueError("sweeps and measurement_interval must be positive")
    quality = quality_max_r > 0
    return f"""# Generated by data/dirichlet_thesis/generate_inputs.py
# Physical Nt={nt}; stored temporal_site_extent L2=Nt+1={nt + 1}.
HeatbathParams:
  L0: {nx}
  L1: {ny}
  L2: {nt + 1}
  L3: 4
  nSweep: {sweeps}
  nOverrelax: 5
  seed: {seed}
  start: "hot"
  temporal_dirichlet: true
  configuration_input: ""
  configuration_output: "configuration_final.klft"
  beta: {BETA}
  epsilon1: 0.0
  epsilon2: 0.0

GaugeObservableParams:
  measurement_interval: {measurement_interval}
  measure_plaquette: false
  measure_plaquette_spatial: false
  measure_plaquette_temporal: false
  measure_wilson_loop_temporal: false
  measure_wilson_loop_mu_nu: false
  measure_polyakov_loop: false
  measure_polyakov_correlator: false
  measure_polyakov_susceptibility: false
  measure_retrace_U: false
  measure_retrace_U2: false
  measure_dirichlet_holonomy: true
  measure_dirichlet_plaquette_profiles: {str(not quality).lower()}
  measure_boundary_wilson_loops: {str(not quality).lower()}
  measure_boundary_wilson_all_heights: {str(all_heights).lower()}
  measure_dirichlet_bulk_polyakov: {str(quality).lower()}
  dirichlet_correlator_max_r: 0
  boundary_wilson_max_r: 0
  dirichlet_bulk_polyakov_max_r: {quality_max_r}
  wilson_loop_multihit: 1
  polyakov_loop_multihit: 1
  polyakov_correlator_max_r: 0
  measure_nested_wilson_action: false
  nested_child_offset: [0, 0, 0]
  W_temp_L_T_pairs: []
  W_mu_nu_pairs: []
  W_Lmu_Lnu_pairs: []
  plaquette_filename: "plaquette.out"
  W_temp_filename: "w_temp.out"
  W_mu_nu_filename: "w_mu_nu.out"
  polyakov_loop_filename: "polyakov_loop.out"
  polyakov_correlator_filename: "polyakov_correlator.out"
  polyakov_susceptibility_filename: "polyakov_susceptibility.out"
  RetraceU_filename: "retrace_u.out"
  RetraceU2_filename: "retrace_u2.out"
  dirichlet_holonomy_correlator_filename: "holonomy_correlator.out"
  dirichlet_holonomy_summary_filename: "holonomy_summary.out"
  dirichlet_plaquette_profile_filename: "plaquette_profile.out"
  boundary_wilson_loop_filename: "boundary_wilson.out"
  dirichlet_bulk_polyakov_filename: "bulk_horizontal_polyakov.out"
  nested_wilson_action_filename: "nested_wilson_action.out"
  write_to_file: true

GradientFlowParams:
  enabled: false
"""


def write_run(root: Path, name: str, text: str) -> Path:
    """Create one run directory and input without overwriting existing data."""
    run_directory = root / name
    run_directory.mkdir(parents=True, exist_ok=True)
    input_path = run_directory / "input.yaml"
    if input_path.exists():
        raise FileExistsError(f"refusing to overwrite {input_path}")
    input_path.write_text(text, encoding="utf-8")
    return input_path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output", type=Path, default=Path("data/dirichlet_thesis/runs")
    )
    parser.add_argument("--nt", type=int, nargs="+", default=list(range(2, 13)))
    parser.add_argument("--seeds", type=int, nargs="+", default=list(DEFAULT_SEEDS))
    parser.add_argument("--ns", type=int, default=64)
    parser.add_argument("--sweeps", type=int, default=8000)
    parser.add_argument("--measurement-interval", type=int, default=1)
    parser.add_argument(
        "--only-minimum-heights",
        action="store_true",
        help="measure only H=1 and H=Nt instead of every Wilson-loop height",
    )
    parser.add_argument(
        "--nested-ensemble-layout",
        action="store_true",
        help="write Nt_<Nt>_Ns_<Ns>_b_<beta>/seed_<seed>/ directories",
    )
    parser.add_argument(
        "--quality-benchmark",
        action="store_true",
        help="also generate the expensive Nt=160, 9x160 horizontal-loop check",
    )
    args = parser.parse_args()

    args.output.mkdir(parents=True, exist_ok=True)
    manifest_lines = ["run\tinput\tphysical_Nt\tnx\tny\tseed"]
    for nt in args.nt:
        for seed in args.seeds:
            if args.nested_ensemble_layout:
                ensemble = f"Nt_{nt}_Ns_{args.ns}_b_{beta_tag(BETA)}"
                name = f"{ensemble}/seed_{seed}"
            else:
                name = f"nt_{nt:03d}_seed_{seed}"
            path = write_run(
                args.output,
                name,
                input_text(
                    nx=args.ns,
                    ny=args.ns,
                    nt=nt,
                    seed=seed,
                    sweeps=args.sweeps,
                    measurement_interval=args.measurement_interval,
                    all_heights=not args.only_minimum_heights,
                ),
            )
            manifest_lines.append(
                f"{name}\t{path}\t{nt}\t{args.ns}\t{args.ns}\t{seed}"
            )

    if args.quality_benchmark:
        for seed in args.seeds:
            name = f"quality_nt_160_9x160_seed_{seed}"
            path = write_run(
                args.output,
                name,
                input_text(
                    nx=9,
                    ny=160,
                    nt=160,
                    seed=seed,
                    sweeps=16000,
                    measurement_interval=1,
                    all_heights=False,
                    quality_max_r=48,
                ),
            )
            manifest_lines.append(f"{name}\t{path}\t160\t9\t160\t{seed}")

    (args.output / "manifest.tsv").write_text(
        "\n".join(manifest_lines) + "\n", encoding="utf-8"
    )
    print(f"wrote {len(manifest_lines) - 1} inputs under {args.output}")


if __name__ == "__main__":
    main()
