#!/usr/bin/env python3
"""Generate the immutable fixed-beta/Nt ``Ns=160`` volume check."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(ROOT))
from data.beta_nt_fixed.comparison.provenance.legacy_pilot_inputs import (  # noqa: E402
    generate_inputs as pilot,
)


SWEEPS = 10_000
SMOKE_SWEEPS = 100
PRODUCTION_SEEDS = (98728066, 856366050, 397310628, 411907572)
SMOKE_SEED = 376035314
ENSEMBLE = pilot.Ensemble("anchor_finite_volume_ns160", 2, "3.6", 160)


def input_text(seed: int, sweeps: int) -> str:
    """Return one input using the validated pilot observable set."""
    text = pilot.input_text(ENSEMBLE, seed, sweeps)
    return text.replace(
        "# Generated by data/step3_scan/generate_inputs.py",
        "# Generated by data/step3_fv160/generate_inputs.py",
        1,
    )


def previous_pilot_seeds() -> set[int]:
    """Return seeds already used by the completed pilot."""
    manifest = (
        ROOT
        / "data"
        / "beta_nt_fixed"
        / "comparison"
        / "provenance"
        / "legacy_pilot_inputs"
        / "manifest.tsv"
    )
    with manifest.open(encoding="utf-8", newline="") as stream:
        return {
            int(row["seed"])
            for row in csv.DictReader(stream, delimiter="\t")
        }


def generate(output: Path) -> list[Path]:
    """Write four production inputs and one smoke input without overwriting."""
    seeds = (*PRODUCTION_SEEDS, SMOKE_SEED)
    if len(set(seeds)) != len(seeds):
        raise RuntimeError("finite-volume extension seeds are not unique")
    if set(seeds) & previous_pilot_seeds():
        raise RuntimeError("finite-volume extension reuses a pilot seed")

    pending: list[tuple[Path, str]] = []
    rows: list[dict[str, object]] = []
    ensemble = pilot.ensemble_name(ENSEMBLE)
    for chain_index, seed in enumerate(PRODUCTION_SEEDS):
        run = f"{ensemble}/seed_{seed}"
        relative_input = Path(run) / "input.yaml"
        text = input_text(seed, SWEEPS)
        pending.append((output / relative_input, text))
        rows.append(
            {
                "array_index": chain_index,
                "run": run,
                "input": relative_input.as_posix(),
                "purpose": ENSEMBLE.purpose,
                "physical_Nt": ENSEMBLE.nt,
                "stored_L2": ENSEMBLE.nt + 1,
                "Ns": ENSEMBLE.ns,
                "beta": ENSEMBLE.beta,
                "lambda_squared_tree": format(
                    pilot.lambda_squared_tree(ENSEMBLE), ".12f"
                ),
                "chain_index": chain_index,
                "seed": seed,
                "sweeps": SWEEPS,
                "measurement_interval": pilot.MEASUREMENT_INTERVAL,
                "dirichlet_suite_measurement_interval": (
                    pilot.SUITE_MEASUREMENT_INTERVAL
                ),
                "input_sha256": pilot.sha256_text(text),
            }
        )

    smoke = input_text(SMOKE_SEED, SMOKE_SWEEPS)
    pending.extend(
        (
            (output / "manifest.tsv", pilot.manifest_text(rows)),
            (output / "smoke" / "input.yaml", smoke),
            (
                output / "smoke" / "sha256.txt",
                f"{pilot.sha256_text(smoke)}  input.yaml\n",
            ),
        )
    )
    existing = [path for path, _ in pending if path.exists()]
    if existing:
        raise FileExistsError(f"refusing to overwrite {existing[0]}")
    for path, text in pending:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="")
    return [path for path, _ in pending]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    paths = generate(args.output)
    print("wrote four production inputs and one smoke input")
    print(f"manifest: {args.output / 'manifest.tsv'}")
    print(f"files created: {len(paths)}")


if __name__ == "__main__":
    main()
