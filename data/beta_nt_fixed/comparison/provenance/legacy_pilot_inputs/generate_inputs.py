def sha256_text(text: str) -> str:
    """Return the SHA-256 digest of UTF-8 text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def manifest_text(rows: list[dict[str, object]]) -> str:
    """Serialize manifest rows with stable column order and LF endings."""
    columns = (
        "array_index",
        "run",
        "input",
        "purpose",
        "physical_Nt",
        "stored_L2",
        "Ns",
        "beta",
        "lambda_squared_tree",
        "chain_index",
        "seed",
        "sweeps",
        "measurement_interval",
        "dirichlet_suite_measurement_interval",
        "input_sha256",
    )
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(
        stream, fieldnames=columns, delimiter="\t", lineterminator="\n"
    )
    writer.writeheader()
    writer.writerows(rows)
    return stream.getvalue()


def generate(output: Path) -> list[Path]:
    """Write all campaign inputs and fail before changing an existing target."""
    if len(SEEDS) != 4 * len(GRID) or len(set(SEEDS)) != len(SEEDS):
        raise RuntimeError("the pilot seed table must contain 32 unique seeds")

    pending: list[tuple[Path, str]] = []
    rows: list[dict[str, object]] = []
    array_index = 0
    for ensemble_index, ensemble in enumerate(GRID):
        for chain_index in range(4):
            seed = SEEDS[4 * ensemble_index + chain_index]
            run = f"{ensemble_name(ensemble)}/seed_{seed}"
            relative_input = Path(run) / "input.yaml"
            text = input_text(ensemble, seed)
            pending.append((output / relative_input, text))
            rows.append(
                {
                    "array_index": array_index,
                    "run": run,
                    "input": relative_input.as_posix(),
                    "purpose": ensemble.purpose,
                    "physical_Nt": ensemble.nt,
                    "stored_L2": ensemble.nt + 1,
                    "Ns": ensemble.ns,
                    "beta": ensemble.beta,
                    "lambda_squared_tree": format(
                        lambda_squared_tree(ensemble), ".12f"
                    ),
                    "chain_index": chain_index,
                    "seed": seed,
                    "sweeps": SWEEPS,
                    "measurement_interval": MEASUREMENT_INTERVAL,
                    "dirichlet_suite_measurement_interval": (
                        SUITE_MEASUREMENT_INTERVAL
                    ),
                    "input_sha256": sha256_text(text),
                }
            )
            array_index += 1

    timing_ensemble = GRID[6]
    timing_text = input_text(timing_ensemble, TIMING_SEED, TIMING_SWEEPS)
    pending.append((output / "timing" / "input.yaml", timing_text))
    pending.append((output / "manifest.tsv", manifest_text(rows)))
    pending.append(
        (
            output / "timing" / "sha256.txt",
            f"{sha256_text(timing_text)}  input.yaml\n",
        )
    )

    existing = [path for path, _ in pending if path.exists()]
    if existing:
        raise FileExistsError(f"refusing to overwrite {existing[0]}")
    for path, text in pending:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="")
    return [path for path, _ in pending]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    paths = generate(args.output)
    print(f"wrote {4 * len(GRID)} production inputs and one timing input")
    print(f"manifest: {args.output / 'manifest.tsv'}")
    print(f"files created: {len(paths)}")


if __name__ == "__main__":
    main()
