def beta_tag(beta: str) -> str:
    """Return the campaign's filesystem-safe coupling tag."""
    return beta.replace(".", "p")


def ensemble_name(ensemble: Ensemble) -> str:
    """Return the canonical production-ensemble directory name."""
    return (
        f"Nt_{ensemble.nt}_Ns_{ensemble.ns}_b_{beta_tag(ensemble.beta)}"
    )


def lambda_squared_tree(ensemble: Ensemble) -> Decimal:
    """Return the tree-level slab coupling ``4 Nt / beta``."""
    return Decimal(4 * ensemble.nt) / Decimal(ensemble.beta)


