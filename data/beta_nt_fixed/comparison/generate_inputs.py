def sha256_text(text: str) -> str:
    """Return the SHA-256 digest of UTF-8 text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def manifest_text(rows: list[dict[str, object]]) -> str:
    """Serialize manifest rows with stable columns and LF endings."""
    columns = (
        "array_index",
        "run",
        "physical_Nt",
        "stored_L2",
        "Ns",
        "beta",
        "beta_over_Nt",
        "g3_squared_L",
        "expected_xi",
        "boundary_max_R",
        "chain_index",
        "seed",
        "sweeps",
        "measurement_interval",
        "profile_interval",
        "boundary_interval",
        "input_sha256",
    )
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(
        stream, fieldnames=columns, delimiter="\t", lineterminator="\n"
    )
    writer.writeheader()
    writer.writerows(rows)
    return stream.getvalue()


def previous_seeds(excluded_manifest: Path) -> set[int]:
    """Return every recorded seed in earlier local campaign manifests."""
    seeds: set[int] = set()
    for manifest in ROOT.glob("data/**/manifest.tsv"):
        if manifest == excluded_manifest:
            continue
        with manifest.open(encoding="utf-8", newline="") as stream:
            for row in csv.DictReader(stream, delimiter="\t"):
                if row.get("seed"):
                    seeds.add(int(row["seed"]))
    return seeds


def generate(
    output: Path,
    *,
    seeds: tuple[int, ...] = SEEDS,
    boundary_interval: int = BOUNDARY_INTERVAL,
    smoke_sweeps: int = SMOKE_SWEEPS,
    timing_sweeps: int = TIMING_SWEEPS,
    excluded_manifest: Path | None = None,
) -> list[Path]:
    """Write production, smoke, and timing inputs without overwriting."""
    if len(seeds) != 4 * len(GRID) + 2 or len(set(seeds)) != len(seeds):
        raise RuntimeError("the production seed table must contain 42 values")
    manifest_to_exclude = (
        Path(__file__).parent
        / "provenance"
        / "superseded_cadence20"
        / "manifest.tsv"
        if excluded_manifest is None
        else excluded_manifest
    )
    if set(seeds) & previous_seeds(manifest_to_exclude):
        raise RuntimeError("the production campaign reuses an earlier seed")
    pending: list[tuple[Path, str]] = []
    rows: list[dict[str, object]] = []
    for ensemble_index, ensemble in enumerate(GRID):
        for chain_index in range(4):
            array_index = 4 * ensemble_index + chain_index
            seed = seeds[array_index]
            run = f"{ensemble_name(ensemble)}/seed_{seed}"
            text = input_text(
                ensemble, seed, SWEEPS, boundary_interval=boundary_interval
            )
            pending.append((output / run / "input.yaml", text))
            rows.append(
                {
                    "array_index": array_index,
                    "run": run,
                    "physical_Nt": ensemble.nt,
                    "stored_L2": ensemble.nt + 1,
                    "Ns": ensemble.ns,
                    "beta": ensemble.beta,
                    "beta_over_Nt": ensemble.beta_over_nt,
                    "g3_squared_L": format(ensemble.g3_squared_l, ".12f"),
                    "expected_xi": ensemble.expected_xi,
                    "boundary_max_R": ensemble.boundary_max_r,
                    "chain_index": chain_index,
                    "seed": seed,
                    "sweeps": SWEEPS,
                    "measurement_interval": MEASUREMENT_INTERVAL,
                    "profile_interval": PROFILE_INTERVAL,
                    "boundary_interval": boundary_interval,
                    "input_sha256": sha256_text(text),
                }
            )

    smoke = Ensemble("2.0", 2, 32, 8, "4")
    smoke_text = input_text(
        smoke, seeds[-2], smoke_sweeps, boundary_interval=boundary_interval
    )
    timing_text = input_text(
        GRID[-1], seeds[-1], timing_sweeps, boundary_interval=boundary_interval
    )
    pending.extend(
        (
            (output / "manifest.tsv", manifest_text(rows)),
            (output / "smoke" / "input.yaml", smoke_text),
            (
                output / "smoke" / "sha256.txt",
                f"{sha256_text(smoke_text)}  input.yaml\n",
            ),
            (output / "timing" / "input.yaml", timing_text),
            (
                output / "timing" / "sha256.txt",
                f"{sha256_text(timing_text)}  input.yaml\n",
            ),
            (output / "klft_commit.txt", f"{KLFT_COMMIT}\n"),
        )
    )
    existing = [path for path, _ in pending if path.exists()]
    if existing:
        raise FileExistsError(f"refusing to overwrite {existing[0]}")
    for path, text in pending:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="")
    return [path for path, _ in pending]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--revision", choices=("cadence20", "cadence25"), default="cadence20"
    )
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    base = Path(__file__).parent
    if args.revision == "cadence20":
        output = base if args.output is None else args.output
        paths = generate(output, excluded_manifest=base / "manifest.tsv")
    else:
        output = base / "cadence25" if args.output is None else args.output
        paths = generate(
            output,
            seeds=CADENCE25_SEEDS,
            boundary_interval=CADENCE25_BOUNDARY_INTERVAL,
            smoke_sweeps=CADENCE25_SMOKE_SWEEPS,
            timing_sweeps=CADENCE25_TIMING_SWEEPS,
            excluded_manifest=base / "cadence25" / "manifest.tsv",
        )
    print(f"wrote {4 * len(GRID)} production inputs, smoke, and timing input")
    print(f"manifest: {output / 'manifest.tsv'}")
    print(f"files created: {len(paths)}")


if __name__ == "__main__":
    main()
