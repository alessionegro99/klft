def beta_tag(beta: str) -> str:
    """Return a filesystem-safe beta tag."""
    return beta.replace(".", "p")


def ensemble_name(ensemble: Ensemble) -> str:
    """Return the canonical ensemble directory name."""
    return f"Nt_{ensemble.nt}_Ns_{ensemble.ns}_b_{beta_tag(ensemble.beta)}"


