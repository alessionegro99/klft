@dataclass(frozen=True)
class Ensemble:
    """One continuum-production ensemble."""

    beta_over_nt: str
    nt: int
    ns: int
    boundary_max_r: int
    expected_xi: str

    @property
    def beta(self) -> str:
        """Return beta without binary floating-point conversion."""
        return format(Decimal(self.beta_over_nt) * self.nt, "f")

    @property
    def g3_squared_l(self) -> Decimal:
        """Return ``g_3^2 L = 4 / (beta/Nt)``."""
        return Decimal(4) / Decimal(self.beta_over_nt)


